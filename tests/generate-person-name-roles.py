#!/usr/bin/env python3
"""Generate independent Latin token priors from public-domain US Census data.

Input: dist.male.first, dist.female.first and dist.all.last downloaded from
https://www2.census.gov/topics/genealogy/1990surnames/ .
A first-name percentage describes one sex; surname percentages describe both.
Keep entries with a nonzero published percentage and compare equal populations.
These population priors are a heuristic, not an Apple name dictionary.
"""
import argparse
from collections import defaultdict
from decimal import Decimal
from pathlib import Path
p = argparse.ArgumentParser()
p.add_argument('data_directory', type=Path)
p.add_argument('output', type=Path)
a = p.parse_args()
frequencies = defaultdict(lambda: [0, 0])
for name, column in [('dist.male.first', 0), ('dist.female.first', 0), ('dist.all.last', 1)]:
    for line in (a.data_directory / name).read_text().splitlines():
        token, frequency, _, _ = line.split()
        frequencies[token.lower()][column] += int(Decimal(frequency) * 1000)
rows = []
for token, (given, family) in sorted(frequencies.items()):
    if not (given or family):
        continue
    assert token.isascii() and token.isalpha() and len(token) <= 13
    rows.append('"' + ('g' if given >= 2 * family else 'f') + token + '"')
text = '''/* Generated by tests/generate-person-name-roles.py from public-domain
 * US Census 1990 name-frequency files. See tests/person-name-parsing.md.
 * Fixed-width rows avoid runtime allocation and pointer relocations. */
static const char latinNameRoles[][15] = {
'''
text += '\n'.join('    ' + ', '.join(rows[i:i+6]) + ',' for i in range(0, len(rows), 6))
a.output.write_text(text + '\n};\n')
print(f'{len(rows)} token priors, {len(rows) * 15} read-only bytes')
